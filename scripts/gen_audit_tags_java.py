"""Generate the engine's AUDIT_TAGS and title patterns from the Python table (RDR-238 Phase 1 Step 1, nexus-qo7ie.6).

One source: ``src/nexus/tables/audit-tags.toml``. ``MemoryRepository.replaceMemory`` refuses a
``replaces`` whose target carries one of these tags or whose title matches one of these patterns;
the sets are never hand-kept. Two pins keep the generated file honest:
``tests/test_audit_tags_java_current.py`` (the file equals what this script renders now) and
``AuditTagsTest`` (the Java sets equal the TOML, parsed by the test itself).

Regenerate after a table edit:

    uv run python scripts/gen_audit_tags_java.py --write

Verify without writing (what the Python pin does):

    uv run python scripts/gen_audit_tags_java.py --check
"""
from __future__ import annotations

import argparse
import pathlib
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
OUTPUT = (
    REPO_ROOT / "service" / "src" / "main" / "java" / "dev" / "nexus" / "service" / "db" / "AuditTags.java"
)


def java_string(text: str) -> str:
    """A Java string literal for *text* (backslash and quote escaped)."""
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render() -> str:
    """The Java source for the current table, byte for byte."""
    sys.path.insert(0, str(REPO_ROOT / "src"))
    from nexus.tables import audit_tags as at  # noqa: PLC0415 — path set just above

    tags = ",\n".join(f"        {java_string(t)}" for t in sorted(at.AUDIT_TAGS))
    patterns = ",\n".join(f"        {java_string(p)}" for p in at.TITLE_PATTERNS)
    return (
        "// SPDX-License-Identifier: AGPL-3.0-or-later\n"
        "// Copyright (c) 2026 Hal Hildebrand. All rights reserved.\n"
        "// GENERATED by scripts/gen_audit_tags_java.py from\n"
        "// src/nexus/tables/audit-tags.toml (RDR-238 Phase 1 Step 1, nexus-qo7ie.6). Do not edit:\n"
        "// change the table and regenerate. AuditTagsTest pins this file to the table.\n"
        "package dev.nexus.service.db;\n\n"
        "import java.util.ArrayList;\n"
        "import java.util.List;\n"
        "import java.util.Optional;\n"
        "import java.util.Set;\n"
        "import java.util.regex.Pattern;\n\n"
        "/**\n"
        " * The tags and title patterns that mark a T2 memory row as an audit record (RDR-238).\n"
        " * {@code MemoryRepository.replaceMemory} refuses a {@code replaces} whose target carries one of\n"
        " * the tags or whose title matches one of the patterns. {@code nx memory curate --t2} reads the\n"
        " * same table on the Python side.\n"
        " *\n"
        " * <p><b>Tag rule.</b> A row's tags are one string. The rule: split on ',', trim each element (the\n"
        " * {@link String#trim()} rule: characters at or below U+0020), drop empty elements, and compare\n"
        " * each element for exact, case-sensitive equality with a member of {@link #AUDIT_TAGS}. A whole tag,\n"
        " * never a substring: {@code gates} and {@code kind:gate-x} are not audit tags, and {@code Gate} is\n"
        " * not {@code gate}. Only the tags string is read, never the row's content.\n"
        " *\n"
        " * <p><b>Title rule (the backstop for older untagged audit rows).</b> Each entry of\n"
        " * {@link #TITLE_PATTERN_SOURCES} is one regular expression, searched anywhere in the title\n"
        " * ({@code find()}, not {@code matches()}), case-insensitively and ASCII-only\n"
        " * ({@link Pattern#CASE_INSENSITIVE}, with {@link Pattern#UNIX_LINES} so that '$' matches only before a\n"
        " * final '\\n', as Python's does). A token entry is a whole word bounded by the start or end of\n"
        " * the title or by '-', '_', '.', ':' or a space on each side. No entry may put a quantifier (star, plus, brace) after a\n"
        " * group: Java's regex engine recurses per character on such a group and overflows the stack.\n"
        " */\n"
        "public final class AuditTags {\n\n"
        "    private AuditTags() {}\n\n"
        "    /** The audit tags, matched as whole tags (see the class comment). */\n"
        "    public static final Set<String> AUDIT_TAGS = Set.of(\n"
        f"{tags});\n\n"
        "    /** The title patterns' source text, in table order. */\n"
        "    public static final List<String> TITLE_PATTERN_SOURCES = List.of(\n"
        f"{patterns});\n\n"
        "    private static final List<Pattern> TITLE_PATTERNS = TITLE_PATTERN_SOURCES.stream()\n"
        "            .map(p -> Pattern.compile(p, Pattern.CASE_INSENSITIVE | Pattern.UNIX_LINES))\n"
        "            .toList();\n\n"
        "    /** The audit tags {@code tags} carries, in the order they appear (empty when none). */\n"
        "    public static List<String> auditTagsOf(String tags) {\n"
        "        List<String> found = new ArrayList<>();\n"
        "        if (tags == null || tags.isEmpty()) {\n"
        "            return found;\n"
        "        }\n"
        "        for (String part : tags.split(\",\", -1)) {\n"
        "            String tag = part.trim();\n"
        "            if (!tag.isEmpty() && AUDIT_TAGS.contains(tag)) {\n"
        "                found.add(tag);\n"
        "            }\n"
        "        }\n"
        "        return found;\n"
        "    }\n\n"
        "    /** The source text of the first title pattern that matches {@code title}, if any. */\n"
        "    public static Optional<String> titlePatternOf(String title) {\n"
        "        if (title == null || title.isEmpty()) {\n"
        "            return Optional.empty();\n"
        "        }\n"
        "        for (int i = 0; i < TITLE_PATTERNS.size(); i++) {\n"
        "            if (TITLE_PATTERNS.get(i).matcher(title).find()) {\n"
        "                return Optional.of(TITLE_PATTERN_SOURCES.get(i));\n"
        "            }\n"
        "        }\n"
        "        return Optional.empty();\n"
        "    }\n"
        "}\n"
    )


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="write the generated file")
    mode.add_argument("--check", action="store_true", help="exit 1 when the file is not current")
    args = ap.parse_args(argv)
    text = render()
    if args.write:
        OUTPUT.write_bytes(text.encode("utf-8"))  # LF endings on every platform
        sys.stdout.write(f"wrote {OUTPUT.relative_to(REPO_ROOT)}\n")
        return 0
    current = OUTPUT.read_bytes() if OUTPUT.exists() else b""
    if current != text.encode("utf-8"):
        sys.stderr.write(
            f"{OUTPUT} is not current; run `uv run python scripts/gen_audit_tags_java.py --write`\n"
        )
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
