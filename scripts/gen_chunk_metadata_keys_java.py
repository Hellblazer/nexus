"""Generate the engine's chunk-metadata key sets from the Python key table (RDR-236 Phase 0, nexus-qyx35).

One source: ``src/nexus/tables/chunk-metadata-keys.toml``. The Phase 4 engine check
(``chunk_metadata_key_refused``) reads these sets beside ``ManifestLabelStage.LABEL_KEYS``;
they are never hand-kept. Two pins keep the generated file honest:
``tests/test_chunk_metadata_keys_java_current.py`` (the file equals what this script renders
now) and ``ChunkMetadataKeysTest`` (the Java sets equal the TOML, parsed by the test itself).

Regenerate after a table edit:

    uv run python scripts/gen_chunk_metadata_keys_java.py --write

Verify without writing (what the Python pin does):

    uv run python scripts/gen_chunk_metadata_keys_java.py --check
"""
from __future__ import annotations

import argparse
import pathlib
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
OUTPUT = (
    REPO_ROOT / "service" / "src" / "main" / "java" / "dev" / "nexus" / "service" / "vectors"
    / "ChunkMetadataKeys.java"
)
#: The classes whose metadata keys become a Java set, in the order they are emitted.
CLASSES = ("CHUNK", "DOCUMENT", "POSITION", "ROW", "LEGACY")

_DOC = {
    "CHUNK": "Keys a chunk row keeps: the chash or the embedding model determines them. Stay.",
    "DOCUMENT": "Keys a catalog document determines. Their home is the catalog; they leave the row.",
    "POSITION": "Keys one manifest position determines. Their home is the manifest; they leave the row.",
    "ROW": "Keys the engine writes on the physical row (quarantine). A client write is refused.",
    "LEGACY": "Retired keys, readable on old rows and swept.",
}


def _literal_set(name: str, keys: list[str]) -> str:
    body = ",\n".join(f'        "{k}"' for k in keys)
    return (
        f"    /** {_DOC[name]} */\n"
        f"    public static final Set<String> {name} = Set.of(\n{body});\n"
    )


def render() -> str:
    """The Java source for the current table, byte for byte."""
    sys.path.insert(0, str(REPO_ROOT / "src"))
    from nexus.tables import chunk_metadata_keys as ckm  # noqa: PLC0415 — path set just above

    parts = [
        "// SPDX-License-Identifier: AGPL-3.0-or-later\n"
        "// Copyright (c) 2026 Hal Hildebrand. All rights reserved.\n"
        "// GENERATED by scripts/gen_chunk_metadata_keys_java.py from\n"
        "// src/nexus/tables/chunk-metadata-keys.toml (RDR-236 Phase 0, nexus-qyx35). Do not edit:\n"
        "// change the table and regenerate. ChunkMetadataKeysTest pins this file to the table.\n"
        "package dev.nexus.service.vectors;\n\n"
        "import java.util.Set;\n\n"
        "/**\n"
        " * The chunk-metadata key table by class (RDR-236). The engine check added in Phase 4 admits the\n"
        " * {@link #CHUNK} and {@link #ROW} keys on a chunk row and names the home of the others in its\n"
        " * {@code chunk_metadata_key_refused} 422. Only metadata keys are listed here; the table's columns,\n"
        " * tables and catalog rows are not. The bypass prefixes (taxonomy, quarantine) are deliberately NOT\n"
        " * generated: a collection-prefix string literal is a parse site that {@code CollectionParseGateTest}\n"
        " * counts down, never up, so the Phase 4 check resolves the bypass another way.\n"
        " */\n"
        "public final class ChunkMetadataKeys {\n\n"
        "    private ChunkMetadataKeys() {}\n"
    ]
    for cls in CLASSES:
        parts.append("\n" + _literal_set(cls, sorted(ckm.keys_of(cls))))
    parts.append("}\n")
    return "".join(parts)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="write the generated file")
    mode.add_argument("--check", action="store_true", help="exit 1 when the file is not current")
    args = ap.parse_args(argv)
    text = render()
    if args.write:
        OUTPUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUTPUT.relative_to(REPO_ROOT)}")
        return 0
    current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
    if current != text:
        print(
            f"{OUTPUT} is not current; run "
            "`uv run python scripts/gen_chunk_metadata_keys_java.py --write`",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
