"""Emit a psql script that runs the three RDR-229 P2.10 residue-repair data moves against ANY database, with no engine.

The moves are registered by ``service/src/main/resources/db/changelog/catalog-049-note-uri-residue.xml`` (changeset
``catalog-049-2``); the engine's worker normally runs them after boot. This script reads that file, so the SQL it emits
is the shipped template, verification, chunk size and ``sleep_ms``, never a copy, and runs each move the way the worker
does: one dml_utils ``run_migration_chunks_committing`` CALL per tenant, threads 1, alias ``t``, chunking ``primary_key``,
with the tenant in ``nexus.tenant`` (the tables are FORCE row level security). It also prints each run's progress and
each move's verification (the rows that still match the rule with a free new value; must be 0).

Usage::

    scripts/p210_residue_moves_sql.py --tenant default --tenant acme > run.sql      # explicit tenants
    scripts/p210_residue_moves_sql.py --tenant-query                  > tenants.sql  # lists the tenants holding rows
    scripts/p210_residue_moves_sql.py --register-only                 > register.sql # the registering INSERT, verbatim
    psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f run.sql

Options: ``--sleep-ms N`` overrides the shipped ``sleep_ms`` (the worker's ``NX_DATA_MOVE_SLEEP_MS`` does the same);
``--chunk-size N`` overrides the chunk size, for a timing sweep; ``--moves a,b`` runs a subset (default all three, in order).

Prerequisites on the target (all true on a database an engine with the 0.1.194+ data-move code has booted on):
the dml_utils and ddl_utils libraries and ``pg_background`` are installed; connect as the migrating role (``nexus_admin``
in the cloud), which holds ``dml_utils_caller``; ``dml_utils_owner`` holds USAGE on schema nexus and SELECT on the three
driving tables (the worker grants this at its pass start; ``--grants`` emits the same GRANTs); the owner-read SELECT
policies of ``catalog-050`` exist (the verification and the tenant list read every tenant's rows). The script must run
outside a transaction block (psql autocommit, the default): the procedure commits each chunk itself. The CALL runs for
as long as the move does and can be stopped and re-run: dml_utils resumes a run by its label.

ORDER MATTERS: ``catalog_documents`` first, then ``document_aspects`` and ``document_highlights``, because a satellite row
is repaired only where its document was.

Progress while a CALL runs (another session)::

    SELECT label, chunk_size, sleep_ms, boundary_count, completed_boundary_count, error_count, started_at, completed_at
      FROM dml_utils.migration_run_summary('rdr229-residue-catalog-documents/<tenant>');
    SELECT * FROM dml_utils.migration_errors((SELECT run_id FROM dml_utils_data.migration_run
                                               WHERE label = 'rdr229-residue-catalog-documents/<tenant>' AND archived_at IS NULL));

To run the same moves through the engine instead, boot an engine that carries catalog-049 on the database: Liquibase
registers ``rdr229-residue-catalog-documents``, the worker runs it, and its ``on_complete`` registers the other two. Read
them with ``SELECT label, chunk_size, sleep_ms, completed_at, failed_at, failure FROM nexus.data_moves``.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

CHANGESET = (Path(__file__).resolve().parent.parent
             / "service/src/main/resources/db/changelog/catalog-049-note-uri-residue.xml")

ORDER = ["rdr229-residue-catalog-documents", "rdr229-residue-document-aspects", "rdr229-residue-document-highlights"]

_MOVE = re.compile(
    r"\('(?P<label>rdr229-residue-[a-z-]+)',\s*\$t\$(?P<template>.*?)\$t\$,\s*"
    r"'(?P<schema>[a-z_]+)', '(?P<table>[a-z_]+)', (?P<chunk>\d+), (?P<sleep>\d+), (?P<timeout>\d+),\s*"
    r"\$v\$(?P<verification>.*?)\$v\$",
    re.DOTALL,
)


def read_moves(path: Path = CHANGESET) -> dict[str, dict[str, str]]:
    text = path.read_text()
    moves = {m.group("label"): m.groupdict() for m in _MOVE.finditer(text)}
    missing = [label for label in ORDER if label not in moves]
    if missing:
        raise SystemExit(f"{path}: no registering INSERT found for {missing}")
    return moves


def registering_insert(path: Path = CHANGESET) -> str:
    text = path.read_text()
    start = text.index('<changeSet id="catalog-049-2"')
    body = text[text.index("<![CDATA[", start) + len("<![CDATA["):]
    return body[: body.index("]]>")].strip() + "\n"


def _lit(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def emit(moves: dict[str, dict[str, str]], names: list[str], tenants: list[str], tenant_query: bool,
         sleep_ms: int | None, chunk_size: int | None, grants: bool) -> str:
    out: list[str] = [
        "-- RDR-229 P2.10 residue repair moves, generated by scripts/p210_residue_moves_sql.py from catalog-049-2.",
        "-- Run with: psql \"$DATABASE_URL\" -v ON_ERROR_STOP=1 -f <this file>   (autocommit; no BEGIN around it)",
        "\\set ECHO queries",
        "\\timing on",
        "SELECT now() AS started_at, current_user AS connected_as;",
    ]
    if grants:
        out.append("GRANT USAGE ON SCHEMA nexus TO dml_utils_owner;")
        for name in names:
            out.append(f"GRANT SELECT ON TABLE nexus.{moves[name]['table']} TO dml_utils_owner;")
    if tenant_query:
        # psql cannot loop a CALL: list the tenants, then re-run with one --tenant each
        out += ["SELECT DISTINCT tenant_id FROM nexus.catalog_documents ORDER BY tenant_id;"]
        return "\n".join(out) + "\n"
    for name in names:
        m = moves[name]
        chunk = chunk_size if chunk_size is not None else int(m["chunk"])
        sleep = sleep_ms if sleep_ms is not None else int(m["sleep"])
        out.append(f"\n-- ===== {name}: {m['schema']}.{m['table']} chunk_size {chunk} sleep_ms {sleep} "
                   f"(shipped sizing: measured on a PITR fork) =====")
        for tenant in tenants:
            label = f"{name}/{tenant}"
            out += [
                f"SELECT set_config('nexus.tenant', {_lit(tenant)}, false);",
                f"SELECT clock_timestamp() AS t0, {_lit(label)} AS run;",
                "CALL dml_utils.run_migration_chunks_committing(",
                f"  i_sql_text => $tpl${m['template']}$tpl$,",
                f"  i_driving_table_schema_name => {_lit(m['schema'])},",
                f"  i_driving_table_name => {_lit(m['table'])},",
                f"  i_label => {_lit(label)},",
                f"  i_chunk_size => {chunk},",
                "  i_threads => 1,",
                "  i_driving_table_alias => 't',",
                "  i_chunk_by => 'primary_key',",
                "  i_poll_timeout_ms => 1,",
                f"  i_sleep_ms => {sleep},",
                "  i_boundary_key_index => NULL,",
                "  i_partition_wise => false);",
                "SELECT set_config('nexus.tenant', '', false);",
                "SELECT clock_timestamp() AS t1;",
                "SELECT label, chunk_size, sleep_ms, boundary_count, completed_boundary_count, error_count, "
                "started_at, completed_at, completed_at - started_at AS elapsed",
                f"  FROM dml_utils.migration_run_summary({_lit(label)});",
            ]
        out += [
            f"\n-- verification of {name}: rows still matching the rule with a free new value; must be 0 (table-wide)",
            "SELECT count(*) AS still_matching FROM (",
            m["verification"].replace("$1", "NULL::text"),
            ") v;",
        ]
    out.append("\nSELECT now() AS finished_at;")
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--tenant", action="append", default=[], help="a tenant to run for (repeatable)")
    ap.add_argument("--tenant-query", action="store_true", help="emit only a query that lists the tenants holding rows")
    ap.add_argument("--register-only", action="store_true", help="emit the registering INSERT of catalog-049-2, verbatim")
    ap.add_argument("--grants", action="store_true", help="also emit the GRANTs to dml_utils_owner the worker makes")
    ap.add_argument("--sleep-ms", type=int, default=None)
    ap.add_argument("--chunk-size", type=int, default=None)
    ap.add_argument("--moves", default=",".join(ORDER), help="comma list of move labels, in order")
    args = ap.parse_args(argv)
    if args.register_only:
        sys.stdout.write(registering_insert())
        return 0
    names = [n.strip() for n in args.moves.split(",") if n.strip()]
    moves = read_moves()
    unknown = [n for n in names if n not in moves]
    if unknown:
        ap.error(f"unknown move(s) {unknown}; known: {ORDER}")
    if not args.tenant and not args.tenant_query:
        ap.error("name a tenant with --tenant (repeatable), or use --tenant-query to list them")
    sys.stdout.write(emit(moves, names, args.tenant, args.tenant_query, args.sleep_ms, args.chunk_size, args.grants))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
