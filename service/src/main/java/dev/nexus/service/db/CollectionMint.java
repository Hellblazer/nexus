/**
 * The engine mints a collection's id and label when it is registered by attributes alone (RDR-229 item 8, P3.8, bead
 * nexus-p2m1x.28); {@link CatalogRepository} (over its size ceiling) delegates here. The design of record is T2
 * {@code nexus_rdr/229-p3.8-design-gate-v2-2026-11-21}, accepted by Sam 2026-11-21.
 *
 * <p><b>The mint</b> ({@link #mint}), in the caller's one transaction:
 * <ol>
 * <li>Read the live row of the tuple {@code (content_type, owner_id, embedding_model, model_version)}: the rows
 *     {@code collectionForTuple} considers, {@code superseded_by = ''} and {@code lifecycle_state <> 'quarantine'}.
 *     When there is one, return it and mint nothing.</li>
 * <li>Otherwise {@link MintedLabel#choose} draws {@code nextval} of the column's own sequence until the label of the
 *     drawn id is free, heals a sequence behind the data once, and refuses (409) on a second collision.</li>
 * <li>One INSERT writes the drawn id and the label together (the column is {@code GENERATED BY DEFAULT AS IDENTITY}, so
 *     no {@code OVERRIDING SYSTEM VALUE}). With the partial UNIQUE index {@value CollectionTupleIndexProbe#INDEX}
 *     (changeset {@code collections-001-2}) the insert is {@code ON CONFLICT (...) WHERE ... DO NOTHING}, and a
 *     lost race is a re-read of the winner's row: two concurrent first mints make one row with no lock. Before that
 *     changeset has applied, {@code ON CONFLICT} on that index would raise 42P10 (no matching unique index), so the
 *     mint takes a per-tuple {@code pg_advisory_xact_lock}, re-reads, and inserts plainly.</li>
 * </ol>
 * The mint never parses a name ({@code CollectionParseGateTest}): the label is {@code "c" + id}.
 *
 * <p><b>No route takes a {@code collection_id}.</b> {@link #refuseSuppliedId} is the one check every registering route
 * calls; the id of every row comes from the sequence.
 *
 * <p><b>A row that would hold a live tuple another collection holds</b> ({@link #refuseLiveTupleConflicts}, an import;
 * {@link #refuseHeldTuple}, a named upsert; the restore load's own check): refused naming both collections, in BOTH
 * index states. With the partial UNIQUE index present the refusal replaces its bare unique violation. Before it exists
 * the same check runs under the per-tuple advisory lock the nameless mint takes ({@link #lockTuple}), locks taken in
 * one sorted order so two batches cannot deadlock, and then re-reads the tuple: an import, a restore or a named
 * registration never creates a second live row on a tuple, and one racing a mint of that tuple leaves one row. (An
 * install that predates the re-own move may already hold D4's accepted duplicate; this refuses to make another, it does
 * not touch the old one.)
 */
public final class CollectionMint {

    private static final Logger log = LoggerFactory.getLogger(CollectionMint.class);

    /** The sequence behind {@code catalog_collections.collection_id}. */
    private static final Field<Object> SEQUENCE = DSL.function("pg_get_serial_sequence", String.class,
            DSL.val("nexus.catalog_collections"), DSL.val("collection_id"))
        .cast(new DefaultDataType<>(SQLDialect.POSTGRES, Object.class, "regclass"));

    /** A registering row would hold a live tuple another collection already holds: a 409 naming both. */
    public static final class LiveTupleConflict extends RuntimeException {
        public LiveTupleConflict(String message) {
            super(message);
        }
    }

    private CollectionMint() {
    }

    private static String nne(String v) {
        return v != null ? v : "";
    }

    // ── no client-supplied id ───────────────────────────────────────────────────────────────────

    /**
     * Refuse a request body that names a {@code collection_id}: the id is assigned by the engine, from the sequence.
     * A 400 ({@link IllegalArgumentException}) on every route that registers a collection row.
     */
    static void refuseSuppliedId(Map<String, Object> coll) {
        if (coll != null && coll.containsKey("collection_id")) {
            throw new IllegalArgumentException("collection_id is assigned by the engine and is not accepted in a request "
                + "(collection '" + CatalogRepository.s(coll, "name") + "'); drop it from the body");
        }
    }

    // ── the mint ────────────────────────────────────────────────────────────────────────────────

    /**
     * Register {@code coll} by its attributes and answer the row: the existing live row of its tuple, or a new one with
     * a minted {@code collection_id} and label. Required: {@code content_type}, {@code owner_id}, {@code embedding_model}
     * and {@code model_version}. The caller's transaction scopes {@code ctx} to {@code tenant}.
     *
     * @param clientRoute the client's route: a mint registers {@code live} collections only (never a quarantine one,
     *                    whose label would have to start {@code quarantine-})
     */
    static Map<String, Object> mint(DSLContext ctx, String tenant, Map<String, Object> coll, boolean clientRoute) {
        refuseSuppliedId(coll);
        String contentType = CatalogRepository.s(coll, "content_type");
        if (contentType == null || contentType.isBlank()) {
            throw new CatalogRepository.EmbeddingProfileConflictException(
                "registering a collection by attributes requires content_type; none was supplied");
        }
        String owner = CatalogRepository.s(coll, "owner_id");
        if (owner == null || owner.isBlank()) {
            throw new IllegalArgumentException("registering a collection by attributes requires owner_id; none was supplied");
        }
        String requestedModel = CatalogRepository.s(coll, "embedding_model");
        if (requestedModel == null || requestedModel.isBlank()) {
            throw new CatalogRepository.EmbeddingProfileConflictException(
                "registering a collection by attributes requires embedding_model; none was supplied");
        }
        String version = CatalogRepository.s(coll, "model_version");
        if (version == null || version.isBlank()) {
            throw new IllegalArgumentException(
                "registering a collection by attributes requires model_version; none was supplied");
        }
        String state = CollectionRegistration.explicitLifecycleState(coll);
        if (state == null) {
            state = "live";
        }
        if ("quarantine".equals(state)) {
            throw new IllegalArgumentException("a minted collection cannot be a quarantine collection: its label would "
                + "have to start quarantine-");
        }

        Map<String, Object> live = liveRow(ctx, tenant, contentType, owner, requestedModel, version);
        if (live != null) {
            return live;
        }
        var model = CollectionRegistration.resolveNewRowModel(ctx, tenant, contentType, requestedModel, "<minted>");
        boolean indexed = tupleIndexExists(ctx);
        if (!indexed) {
            // The partial index is not built yet (the engine booted before the re-own move completed): ON CONFLICT on it
            // would raise 42P10. Serialize the first mints of this tuple, then look again.
            lockTuple(ctx, tenant, contentType, owner, requestedModel, version);
            live = liveRow(ctx, tenant, contentType, owner, requestedModel, version);
            if (live != null) {
                return live;
            }
        }

        MintedLabel.Choice choice = MintedLabel.choose(
            () -> ctx.fetchValue(DSL.function("nextval", Long.class, SEQUENCE)),
            id -> ctx.fetchExists(ctx.selectOne().from(CATALOG_COLLECTIONS).where(CATALOG_COLLECTIONS.COLLECTION_ID.eq(id))),
            label -> ctx.fetchExists(ctx.selectOne().from(CATALOG_COLLECTIONS)
                .where(CATALOG_COLLECTIONS.TENANT_ID.eq(tenant).and(CATALOG_COLLECTIONS.NAME.eq(label)))),
            colliding -> healSequence(ctx, tenant, colliding));

        var insert = ctx.insertInto(CATALOG_COLLECTIONS,
                CATALOG_COLLECTIONS.TENANT_ID, CATALOG_COLLECTIONS.NAME, CATALOG_COLLECTIONS.COLLECTION_ID,
                CATALOG_COLLECTIONS.CONTENT_TYPE, CATALOG_COLLECTIONS.OWNER_ID, CATALOG_COLLECTIONS.EMBEDDING_MODEL,
                CATALOG_COLLECTIONS.MODEL_VERSION, CATALOG_COLLECTIONS.DISPLAY_NAME, CATALOG_COLLECTIONS.LEGACY_GRANDFATHERED,
                CATALOG_COLLECTIONS.SUPERSEDED_BY, CATALOG_COLLECTIONS.CREATED_AT,
                CATALOG_COLLECTIONS.DIMENSION, CATALOG_COLLECTIONS.LIFECYCLE_STATE)
            .values(tenant, choice.label(), choice.collectionId(), contentType, owner, model.model(), version,
                nne(CatalogRepository.s(coll, "display_name")), false, "",
                java.time.OffsetDateTime.now(java.time.ZoneOffset.UTC),
                model.dimension(), state);
        int inserted = indexed
            ? insert.onConflict(CATALOG_COLLECTIONS.TENANT_ID, CATALOG_COLLECTIONS.CONTENT_TYPE, CATALOG_COLLECTIONS.OWNER_ID,
                    CATALOG_COLLECTIONS.EMBEDDING_MODEL, CATALOG_COLLECTIONS.MODEL_VERSION)
                // inlined, not bound: the inference predicate must be provably the index's own, and a bind parameter is
                // not a constant at parse time (42P10)
                .where(CATALOG_COLLECTIONS.SUPERSEDED_BY.eq(DSL.inline(""))
                    .and(CATALOG_COLLECTIONS.LIFECYCLE_STATE.ne(DSL.inline("quarantine"))))
                .doNothing().execute()
            : insert.execute();
        Map<String, Object> row = liveRow(ctx, tenant, contentType, owner, requestedModel, version);
        if (row == null) {
            throw new IllegalStateException("minting a collection for (" + contentType + ", " + owner + ", " + requestedModel
                + ", " + version + "): the insert reported " + inserted + " rows and no live row of the tuple is visible");
        }
        return row;
    }

    /**
     * Heal the sequence once, forward only. The sequence is shared by every tenant and this tenant sees only its own rows,
     * so the floor is the largest of this tenant's ids and the colliding id; the definer function
     * {@code nexus.collection_id_seq_heal} (changeset {@code collections-002}) draws the sequence forward with
     * {@code nextval} until it has drawn the floor. It never calls {@code setval}, so a draw by another session while it
     * runs cannot be set back and no id is handed out twice; it leaves the sequence alone when it is already past the
     * floor. A floor more than the function's bound (100000 draws) above the sequence is refused, with the gap and the
     * operator remedy in the message: that refusal is a {@link MintedLabel.SequenceBehindDataException}, the mint's 409,
     * message intact.
     */
    private static void healSequence(DSLContext ctx, String tenant, long colliding) {
        Long visibleMax = ctx.select(DSL.max(CATALOG_COLLECTIONS.COLLECTION_ID)).from(CATALOG_COLLECTIONS)
            .where(CATALOG_COLLECTIONS.TENANT_ID.eq(tenant)).fetchOne(0, Long.class);
        Long was = ctx.fetchValue(DSL.function("pg_sequence_last_value", Long.class, SEQUENCE));
        long floor = Math.max(colliding, visibleMax == null ? 0L : visibleMax);
        Long now;
        try {
            now = ctx.fetchValue(DSL.function(DSL.name("nexus", "collection_id_seq_heal"), Long.class, DSL.val(floor)));
        } catch (DataAccessException e) {
            if (e.getCause() instanceof SQLException se && HEAL_REFUSED.equals(se.getSQLState())) {
                throw new MintedLabel.SequenceBehindDataException(refusalText(se));
            }
            throw e;
        }
        log.warn("event=collection_id_sequence_behind_data tenant={} colliding_id={} sequence_was={} sequence_now={}",
            tenant, colliding, was, now);
    }

    /** The SQLSTATE the heal function raises for a refusal (collections-002). */
    static final String HEAL_REFUSED = "NX229";

    /** The refusal's own text, without the driver's {@code ERROR:} prefix or the {@code Where:} trace lines. */
    private static String refusalText(SQLException se) {
        String text = se.getMessage() == null ? "" : se.getMessage();
        int where = text.indexOf("\n  Where:");
        if (where >= 0) {
            text = text.substring(0, where);
        }
        return text.startsWith("ERROR: ") ? text.substring("ERROR: ".length()) : text;
    }

    /**
     * The per-tuple advisory lock of the paths that run before the partial UNIQUE index exists (a mint, an import, a
     * restore): {@code pg_advisory_xact_lock} on a hash of the tuple, held to the end of the caller's transaction.
     */
    static void lockTuple(DSLContext ctx, String tenant, String contentType, String owner, String model, String version) {
        lockKey(ctx, tupleKey(tenant, contentType, owner, model, version));
    }

    static String tupleKey(String tenant, String contentType, String owner, String model, String version) {
        return String.join("\u0001", tenant, contentType, owner, model, version);
    }

    static void lockKey(DSLContext ctx, String key) {
        Field<Long> hashed = DSL.function("hashtextextended", Long.class, DSL.val(key), DSL.val(0L));
        ctx.select(DSL.function("pg_advisory_xact_lock", Object.class, hashed)).fetch();
    }

    /** Every collection's {@code collection_id} by name, for one tenant. */
    static Map<String, Long> idsByName(DSLContext ctx, String tenant) {
        return ctx.select(CATALOG_COLLECTIONS.NAME, CATALOG_COLLECTIONS.COLLECTION_ID).from(CATALOG_COLLECTIONS)
            .where(CATALOG_COLLECTIONS.TENANT_ID.eq(tenant)).fetchMap(CATALOG_COLLECTIONS.NAME, CATALOG_COLLECTIONS.COLLECTION_ID);
    }

    /** The name of another live collection of this tuple (the lowest {@code collection_id}), or null. */
    static String heldBy(DSLContext ctx, String tenant, String contentType, String owner, String model, String version,
                         String exceptName) {
        return ctx.select(CATALOG_COLLECTIONS.NAME).from(CATALOG_COLLECTIONS)
            .where(CATALOG_COLLECTIONS.TENANT_ID.eq(tenant)
                .and(CATALOG_COLLECTIONS.CONTENT_TYPE.eq(contentType))
                .and(CATALOG_COLLECTIONS.OWNER_ID.eq(owner))
                .and(CATALOG_COLLECTIONS.EMBEDDING_MODEL.eq(model))
                .and(CATALOG_COLLECTIONS.MODEL_VERSION.eq(version))
                .and(CATALOG_COLLECTIONS.SUPERSEDED_BY.eq(""))
                .and(CATALOG_COLLECTIONS.LIFECYCLE_STATE.ne("quarantine"))
                .and(CATALOG_COLLECTIONS.NAME.ne(exceptName)))
            .orderBy(CATALOG_COLLECTIONS.COLLECTION_ID.asc()).limit(1).fetchOne(CATALOG_COLLECTIONS.NAME);
    }

    private static Map<String, Object> liveRow(DSLContext ctx, String tenant, String contentType, String owner,
                                               String model, String version) {
        Record r = ctx.select(CATALOG_COLLECTIONS.COLLECTION_ID, CATALOG_COLLECTIONS.NAME, CATALOG_COLLECTIONS.CONTENT_TYPE,
                CATALOG_COLLECTIONS.OWNER_ID, CATALOG_COLLECTIONS.EMBEDDING_MODEL, CATALOG_COLLECTIONS.MODEL_VERSION,
                CATALOG_COLLECTIONS.DISPLAY_NAME, CATALOG_COLLECTIONS.LIFECYCLE_STATE, CATALOG_COLLECTIONS.DIMENSION)
            .from(CATALOG_COLLECTIONS)
            .where(CATALOG_COLLECTIONS.TENANT_ID.eq(tenant)
                .and(CATALOG_COLLECTIONS.CONTENT_TYPE.eq(contentType))
                .and(CATALOG_COLLECTIONS.OWNER_ID.eq(owner))
                .and(CATALOG_COLLECTIONS.EMBEDDING_MODEL.eq(model))
                .and(CATALOG_COLLECTIONS.MODEL_VERSION.eq(version))
                .and(CATALOG_COLLECTIONS.SUPERSEDED_BY.eq(""))
                .and(CATALOG_COLLECTIONS.LIFECYCLE_STATE.ne("quarantine")))
            .orderBy(CATALOG_COLLECTIONS.COLLECTION_ID.asc())
            .limit(1)
            .fetchOne();
        if (r == null) {
            return null;
        }
        Map<String, Object> row = new LinkedHashMap<>();
        row.put("collection_id", r.get(CATALOG_COLLECTIONS.COLLECTION_ID));
        row.put("name", r.get(CATALOG_COLLECTIONS.NAME));
        row.put("content_type", r.get(CATALOG_COLLECTIONS.CONTENT_TYPE));
        row.put("owner_id", r.get(CATALOG_COLLECTIONS.OWNER_ID));
        row.put("embedding_model", r.get(CATALOG_COLLECTIONS.EMBEDDING_MODEL));
        row.put("model_version", r.get(CATALOG_COLLECTIONS.MODEL_VERSION));
        row.put("display_name", nne(r.get(CATALOG_COLLECTIONS.DISPLAY_NAME)));
        row.put("lifecycle_state", r.get(CATALOG_COLLECTIONS.LIFECYCLE_STATE));
        row.put("dimension", r.get(CATALOG_COLLECTIONS.DIMENSION));
        return row;
    }

    // ── a registering row on a live tuple another collection holds ──────────────────────────────

    /**
     * Refuse the NEW import rows ({@code fresh}: names not yet registered) that would take a live tuple already held by
     * another collection or by an earlier row of the batch, naming both collections. Nothing is written (a
     * {@link LiveTupleConflict}, a 409). With the partial UNIQUE index absent the tuples are locked first (sorted), then
     * re-read, so a concurrent mint, import or named registration of a tuple cannot slip a second row past the check.
     */
    static void refuseLiveTupleConflicts(DSLContext ctx, String tenant, List<Map<String, Object>> fresh) {
        List<String[]> live = new ArrayList<>();   // {name, content_type, owner_id, embedding_model, model_version}
        for (Map<String, Object> coll : fresh) {
            if ("".equals(nne(CatalogRepository.s(coll, "superseded_by")))
                    && !"quarantine".equals(CollectionRegistration.lifecycleStateForImport(coll))) {
                live.add(new String[] {CatalogRepository.s(coll, "name"), nne(CatalogRepository.s(coll, "content_type")),
                    nne(CatalogRepository.s(coll, "owner_id")), nne(CatalogRepository.s(coll, "embedding_model")),
                    CollectionRegistration.importModelVersion(coll)});
            }
        }
        if (live.isEmpty()) {
            return;
        }
        if (!tupleIndexExists(ctx)) {
            live.stream().map(r -> tupleKey(tenant, r[1], r[2], r[3], r[4])).distinct().sorted().forEach(k -> lockKey(ctx, k));
        }
        Map<List<String>, String> seen = new HashMap<>();
        for (String[] r : live) {
            String earlier = seen.putIfAbsent(List.of(r[1], r[2], r[3], r[4]), r[0]);
            if (earlier != null) {
                throw conflict(r[0], earlier, r[1], r[2], r[3], r[4]);
            }
            String held = heldBy(ctx, tenant, r[1], r[2], r[3], r[4], r[0]);
            if (held != null) {
                throw conflict(r[0], held, r[1], r[2], r[3], r[4]);
            }
        }
    }

    /**
     * A NAMED registration of a new live row: refuse it, naming both collections, when another live collection already
     * holds its tuple. With the index absent the tuple is locked first and then re-read. A row that is itself
     * superseded or quarantined holds no live tuple and is not checked.
     */
    static void refuseHeldTuple(DSLContext ctx, String tenant, String name, String contentType, String owner, String model,
                                String version, String lifecycleState, String supersededBy) {
        if (!"".equals(supersededBy) || "quarantine".equals(lifecycleState)) {
            return;
        }
        if (!tupleIndexExists(ctx)) {
            lockTuple(ctx, tenant, contentType, owner, model, version);
        }
        String held = heldBy(ctx, tenant, contentType, owner, model, version, name);
        if (held != null) {
            throw conflict(name, held, contentType, owner, model, version);
        }
    }

    /** Whether the partial UNIQUE index of the live tuple exists (changeset collections-001-2). */
    static boolean tupleIndexExists(DSLContext ctx) {
        return ctx.fetchExists(ctx.selectOne().where(
            DSL.function("to_regclass", Object.class, DSL.val("nexus." + CollectionTupleIndexProbe.INDEX)).isNotNull()));
    }

    /** The refusal naming both collections of a live tuple (also the restore load's). */
    public static LiveTupleConflict conflict(String name, String holder, String contentType, String owner, String model,
                                             String version) {
        return new LiveTupleConflict("collections '" + holder + "' and '" + name + "' are both live for the tuple "
            + "(content_type " + contentType + ", owner_id " + owner + ", embedding_model " + model + ", model_version "
            + version + "); a tuple has one live collection. Rename, supersede or drop one of them, then try again.");
    }
}
