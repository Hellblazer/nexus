package dev.nexus.service.db;

import java.util.function.LongConsumer;
import java.util.function.LongPredicate;
import java.util.function.LongSupplier;
import java.util.function.Predicate;

/**
 * The id and label of a collection the engine mints because it was registered with no label (RDR-229 item 8, P3.8,
 * bead nexus-p2m1x.28), chosen before the one insert that writes both.
 *
 * <p>A pure seam, so the choice is tested without the schema: the caller passes the column's own sequence as
 * {@code nextId} (P3.1's {@code collection_id}, read with {@code nextval(pg_get_serial_sequence(...))}; the insert
 * then writes that id and the label in one statement with no {@code OVERRIDING SYSTEM VALUE}, since the column is
 * {@code GENERATED BY DEFAULT AS IDENTITY}: lead ruling T2 {@code nexus_rdr/229-lead-ruling-collection-id-by-default-2026-11-21};
 * no route accepts a client-supplied {@code collection_id}) and
 * {@code labelTaken} as "a live row of this tenant already has this label". When the label of the drawn id is taken
 * (a pre-existing label of the minted form; P3.6 refuses new ones), the next id is drawn and tried, so
 * {@code label == "c" + collectionId} holds for every minted row and a skipped id is never used (design gate,
 * accepted by Sam 2026-11-21, T2 {@code nexus/sam-ruling-rdr229-p38-design-gate-v2-2026-11-21}).
 *
 * <p>The label is {@link CollectionLabel#mintedLabel} (P3.6, elsinore), the same class that holds the minted-form
 * predicate the label rule refuses a user label by, so the two cannot drift.
 */
public final class MintedLabel {

    /** How many ids a mint draws before it refuses: each extra draw means a live label of the minted form. */
    public static final int MAX_DRAWS = 16;

    /** The id and label a mint inserts together. */
    public record Choice(long collectionId, String label) {
    }

    /**
     * A drawn id was already a row even after the sequence was healed once: something is writing explicit ids
     * concurrently. A 409 on the route. "Even after the heal" covers every tenant's ids only where D2's owner-read policy
     * lets the heal's definer function read them; elsewhere it covers this tenant's.
     */
    public static final class SequenceBehindDataException extends IllegalStateException {
        public SequenceBehindDataException(long id) {
            super("minting a collection: the drawn collection_id " + id + " is already a row after the collection_id"
                + " sequence was drawn forward to the largest collection_id of any tenant the heal can read (every tenant where the"
                + " owner-read policy exists, else this one); something is inserting explicit ids"
                + " concurrently. Check the setval on pg_get_serial_sequence('nexus.catalog_collections','collection_id')");
        }

        /** The heal refused (its message names the gap and the operator remedy): carried through to the 409 as it is. */
        public SequenceBehindDataException(String message) {
            super(message);
        }
    }

    /** Every drawn id's label is a live row's name: a 409 on the route. */
    public static final class LabelsTakenException extends IllegalStateException {
        public LabelsTakenException(String message) {
            super(message);
        }
    }

    private MintedLabel() {
    }

    /**
     * Draw ids from {@code nextId} until one's label is free, at most {@link #MAX_DRAWS} times.
     *
     * <p>{@code idTaken} says whether a row already has the id. The sequence never repeats a value, so a taken id
     * means the sequence is behind the data (an explicit-id insert, as a restore does, with no {@code setval} after
     * it). The id is judged across every tenant (an id is unique across the installation). Then {@code healSequence}
     * runs ONCE with the colliding id: the caller draws the sequence FORWARD with {@code nextval} to the largest
     * {@code collection_id} of any tenant (never {@code setval}, so it cannot move backward past an id another session
     * has just drawn) and logs a WARN ({@code event=collection_id_sequence_behind_data}, old and new values), and the
     * mint draws again. A second
     * taken id refuses (linda's ruling on baton's BY DEFAULT condition, 2026-11-21): never a silent skip, never a raw
     * unique violation, and an install whose restore missed its setval can still create collections.
     *
     * @throws SequenceBehindDataException when a drawn id is a row after the heal (a 409 on the route)
     * @throws LabelsTakenException when every draw's label is taken (a 409 on the route)
     */
    public static Choice choose(LongSupplier nextId, LongPredicate idTaken, Predicate<String> labelTaken,
                                LongConsumer healSequence) {
        boolean healed = false;
        int draws = 0;
        String firstTaken = null;
        while (draws < MAX_DRAWS) {
            long id = nextId.getAsLong();
            if (idTaken.test(id)) {
                if (healed) {
                    throw new SequenceBehindDataException(id);
                }
                healSequence.accept(id);
                healed = true;
                continue;
            }
            draws++;
            String label = CollectionLabel.mintedLabel(id);
            if (!labelTaken.test(label)) {
                return new Choice(id, label);
            }
            if (firstTaken == null) {
                firstTaken = label;
            }
        }
        throw new LabelsTakenException("minting a collection label: the labels of " + MAX_DRAWS
            + " drawn collection ids were all taken, from " + firstTaken
            + "; a row named of the minted form c<digits> is in the way. Rename those collections, then try again.");
    }
}
