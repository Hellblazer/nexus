package dev.nexus.service;

import com.fasterxml.jackson.core.type.TypeReference;
import com.fasterxml.jackson.databind.ObjectMapper;
import dev.nexus.service.db.TenantConstants;
import org.jooq.SQLDialect;
import org.jooq.impl.DSL;
import org.junit.jupiter.api.*;
import org.testcontainers.containers.PostgreSQLContainer;

import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.sql.Connection;
import java.util.List;
import java.util.Map;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * RDR-229 P3.5a, first commit (nexus-p2m1x.23): the catalog collection rows on
 * {@code GET /v1/catalog/collections/list}, {@code /get} and {@code /for_tuple} carry
 * {@code collection_id}, read-only. The value is the registry's own id, the one
 * {@code SELECT collection_id FROM nexus.catalog_collections WHERE tenant_id = ? AND name = ?} reads,
 * as a JSON number. No route takes an id as input.
 *
 * <p>{@code catalog_collections.collection_id} is {@code bigint GENERATED BY DEFAULT AS IDENTITY}
 * (vectors-068-1), and an identity column is NOT NULL: on an engine that has the column the id is
 * always a number, and an older engine sends no key at all. {@link #theRegistryIdColumnIsIdentityAndNotNull}
 * pins that, from a snapshot taken before any test mutates the column.
 *
 * <p>The {@code defensiveNull} tests cover the other direction, a NULL the engine would pass through as an
 * explicit {@code "collection_id": null}, the key present and never omitted. No writer or migration can
 * produce that row, so it is made synthetically: on this class's own throwaway container the identity and
 * the NOT NULL are dropped and one row's id is nulled as the superuser. They prove the pass-through, not
 * that such a row occurs.
 */
@TestInstance(TestInstance.Lifecycle.PER_CLASS)
class CatalogCollectionIdReadTest {

    private static final String TOKEN = "catalog-collection-id-read-token-p35a";
    private static final String SVC_ROLE = "svc_cat_cid_read";
    private static final String SVC_PASS = "svc_cat_cid_read_pass";
    private static final String TENANT = TenantConstants.DEFAULT_TENANT;
    private static final String MODEL = "voyage-context-3";
    private static final TypeReference<Map<String, Object>> MAP_T = new TypeReference<>() {};

    private static final String NUMBERED = "p35a-numbered";
    private static final String NUMBERED_OWNER = "p35a-owner-n";
    private static final String DEFENSIVE_NULL = "p35a-defensive-null";
    private static final String DEFENSIVE_NULL_OWNER = "p35a-owner-d";

    PostgreSQLContainer<?> pg;
    NexusService service;
    HttpClient http;
    com.zaxxer.hikari.HikariDataSource svcDs;
    ObjectMapper mapper;

    /** Read before the defensive-null setup mutates the column; the identity test asserts them. */
    String idColumnIsIdentity;
    String idColumnIsNullable;

    @BeforeAll
    void startAll() throws Exception {
        mapper = new ObjectMapper();
        pg = PgContainerHelper.start();
        try (Connection su = pg.createConnection("")) {
            PgContainerHelper.applyProductSchema(su);
        }
        try (Connection su = pg.createConnection("")) {
            PgContainerHelper.bootstrapServiceRole(su, SVC_ROLE, SVC_PASS);
            PgContainerHelper.seedServiceToken(DSL.using(su, SQLDialect.POSTGRES), TOKEN, TENANT, "test-bound");
        }
        try (Connection su = pg.createConnection("")) {
            var row = DSL.using(su, SQLDialect.POSTGRES).fetchOne(
                "SELECT is_nullable, is_identity FROM information_schema.columns "
                    + "WHERE table_schema = 'nexus' AND table_name = 'catalog_collections' AND column_name = 'collection_id'");
            assertThat(row).as("the column exists").isNotNull();
            idColumnIsIdentity = row.get("is_identity", String.class);
            idColumnIsNullable = row.get("is_nullable", String.class);
        }
        var cfg = new com.zaxxer.hikari.HikariConfig();
        cfg.setJdbcUrl(pg.getJdbcUrl());
        cfg.setUsername(SVC_ROLE);
        cfg.setPassword(SVC_PASS);
        cfg.setMaximumPoolSize(4);
        cfg.setAutoCommit(true);
        svcDs = new com.zaxxer.hikari.HikariDataSource(cfg);
        service = new NexusService(0, TOKEN, svcDs);
        service.start();
        http = TestHttp.client();

        // The tenant's first request runs the once-per-process ghost sweep, which deletes a collection
        // registered but chunkless at that moment (CatalogHandlerRenameTest). Burn it before registering.
        http.send(TestHttp.request("http://127.0.0.1:" + service.getPort() + "/v1/catalog/collections/list")
            .header("Authorization", "Bearer " + TOKEN).GET().build(), HttpResponse.BodyHandlers.ofString());

        register(NUMBERED, NUMBERED_OWNER);
        register(DEFENSIVE_NULL, DEFENSIVE_NULL_OWNER);

        try (Connection su = pg.createConnection("")) {
            var ctx = DSL.using(su, SQLDialect.POSTGRES);
            ctx.execute("ALTER TABLE nexus.catalog_collections ALTER COLUMN collection_id DROP IDENTITY");
            ctx.execute("ALTER TABLE nexus.catalog_collections ALTER COLUMN collection_id DROP NOT NULL");
            int n = ctx.execute("UPDATE nexus.catalog_collections SET collection_id = NULL WHERE name = '" + DEFENSIVE_NULL + "'");
            assertThat(n).as("guard: exactly one row's id is nulled").isEqualTo(1);
        }
    }

    @AfterAll
    void stopAll() throws Exception {
        if (service != null) service.stop();
        if (svcDs != null) svcDs.close();
        if (pg != null) pg.stop();
    }

    private void register(String name, String owner) throws Exception {
        var up = post("/v1/catalog/collections/upsert",
            "{\"name\":\"" + name + "\",\"content_type\":\"knowledge\",\"owner_id\":\"" + owner + "\","
                + "\"embedding_model\":\"" + MODEL + "\",\"model_version\":\"v1\","
                + "\"display_name\":\"\",\"legacy_grandfathered\":true}");
        assertThat(up.statusCode()).as("guard: " + name + " registers").isEqualTo(200);
    }

    /** The registry's own value for one row, read straight from the table as the superuser. */
    private Long registryId(String name) throws Exception {
        try (Connection su = pg.createConnection("")) {
            return DSL.using(su, SQLDialect.POSTGRES).fetchOne(
                "SELECT collection_id FROM nexus.catalog_collections WHERE tenant_id = ? AND name = ?",
                TENANT, name).get(0, Long.class);
        }
    }

    /** Why the defensive-null row is synthetic: on an engine with the column, the id cannot be NULL. */
    @Test
    void theRegistryIdColumnIsIdentityAndNotNull() {
        assertThat(idColumnIsIdentity).isEqualTo("YES");
        assertThat(idColumnIsNullable).isEqualTo("NO");
    }

    // ---- GET /collections/get ------------------------------------------------------------------------------------

    @Test
    void get_carriesTheRegistryIdAsANumber() throws Exception {
        long want = registryId(NUMBERED);
        var row = body(get("/v1/catalog/collections/get?name=" + NUMBERED));
        assertThat(row).containsKey("collection_id");
        assertThat(row.get("collection_id")).isInstanceOf(Number.class);
        assertThat(((Number) row.get("collection_id")).longValue()).isEqualTo(want).isPositive();
    }

    @Test
    void get_defensiveNullIsPassedThroughExplicitly() throws Exception {
        var row = body(get("/v1/catalog/collections/get?name=" + DEFENSIVE_NULL));
        assertThat(row).as("present, never omitted").containsKey("collection_id");
        assertThat(row.get("collection_id")).isNull();
    }

    // ---- GET /collections/list -----------------------------------------------------------------------------------

    @Test
    void list_carriesTheRegistryIdOnEveryRow_andADefensiveNullIsPassedThroughExplicitly() throws Exception {
        long want = registryId(NUMBERED);
        var rows = listRows("/v1/catalog/collections/list");
        var numbered = rows.stream().filter(r -> NUMBERED.equals(r.get("name"))).findFirst().orElseThrow();
        var defensive = rows.stream().filter(r -> DEFENSIVE_NULL.equals(r.get("name"))).findFirst().orElseThrow();
        assertThat(rows).as("every row carries the key").allSatisfy(r -> assertThat(r).containsKey("collection_id"));
        assertThat(numbered.get("collection_id")).isInstanceOf(Number.class);
        assertThat(((Number) numbered.get("collection_id")).longValue()).isEqualTo(want);
        assertThat(defensive.get("collection_id")).isNull();
    }

    // ---- GET /collections/for_tuple ------------------------------------------------------------------------------

    @Test
    void forTuple_carriesTheRegistryIdAsANumber() throws Exception {
        long want = registryId(NUMBERED);
        var row = body(get(forTuple(NUMBERED_OWNER)));
        assertThat(row.get("name")).isEqualTo(NUMBERED);
        assertThat(row).containsKey("collection_id");
        assertThat(row.get("collection_id")).isInstanceOf(Number.class);
        assertThat(((Number) row.get("collection_id")).longValue()).isEqualTo(want);
    }

    @Test
    void forTuple_defensiveNullIsPassedThroughExplicitly() throws Exception {
        var row = body(get(forTuple(DEFENSIVE_NULL_OWNER)));
        assertThat(row.get("name")).isEqualTo(DEFENSIVE_NULL);
        assertThat(row).as("present, never omitted").containsKey("collection_id");
        assertThat(row.get("collection_id")).isNull();
    }

    // ---- read-only -----------------------------------------------------------------------------------------------

    /**
     * Read-only: the id is a response field and not a request one. A get by id alone is still a 400, and a
     * {@code ?collection_id=} on list and for_tuple changes nothing about the answer.
     */
    @Test
    void noRouteTakesAnIdAsInput() throws Exception {
        long id = registryId(NUMBERED);
        long otherId = id + 1_000_000L;

        var byIdOnly = get("/v1/catalog/collections/get?collection_id=" + id);
        assertThat(byIdOnly.statusCode()).as("name is still required; collection_id is not read").isEqualTo(400);

        var listPlain = get("/v1/catalog/collections/list");
        var listWithId = get("/v1/catalog/collections/list?collection_id=" + otherId);
        assertThat(listWithId.statusCode()).isEqualTo(200);
        assertThat(mapper.readValue(listWithId.body(), MAP_T)).as("list ignores ?collection_id=")
            .isEqualTo(mapper.readValue(listPlain.body(), MAP_T));

        var tuplePlain = get(forTuple(NUMBERED_OWNER));
        var tupleWithId = get(forTuple(NUMBERED_OWNER) + "&collection_id=" + otherId);
        assertThat(tupleWithId.statusCode()).isEqualTo(200);
        assertThat(mapper.readValue(tupleWithId.body(), MAP_T)).as("for_tuple ignores ?collection_id=")
            .isEqualTo(mapper.readValue(tuplePlain.body(), MAP_T));
    }

    @SuppressWarnings("unchecked")
    private List<Map<String, Object>> listRows(String path) throws Exception {
        var resp = get(path);
        assertThat(resp.statusCode()).isEqualTo(200);
        return (List<Map<String, Object>>) mapper.readValue(resp.body(), MAP_T).get("collections");
    }

    private Map<String, Object> body(HttpResponse<String> resp) throws Exception {
        assertThat(resp.statusCode()).as(resp.body()).isEqualTo(200);
        return mapper.readValue(resp.body(), MAP_T);
    }

    private static String forTuple(String ownerId) {
        return "/v1/catalog/collections/for_tuple?content_type=knowledge&owner_id=" + ownerId + "&embedding_model=" + MODEL;
    }

    private HttpResponse<String> get(String path) throws Exception {
        var req = TestHttp.request("http://127.0.0.1:" + service.getPort() + path)
            .header("Authorization", "Bearer " + TOKEN)
            .header("X-Nexus-Tenant", TENANT)
            .GET().build();
        return http.send(req, HttpResponse.BodyHandlers.ofString());
    }

    private HttpResponse<String> post(String path, String body) throws Exception {
        var req = TestHttp.request("http://127.0.0.1:" + service.getPort() + path)
            .header("Authorization", "Bearer " + TOKEN)
            .header("X-Nexus-Tenant", TENANT)
            .header("Content-Type", "application/json")
            .POST(HttpRequest.BodyPublishers.ofString(body))
            .build();
        return http.send(req, HttpResponse.BodyHandlers.ofString());
    }
}
