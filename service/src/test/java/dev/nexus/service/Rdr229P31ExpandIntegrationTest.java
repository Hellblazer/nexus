    // ---- the list ----------------------------------------------------------------------------------------------------

    record Row(String table, String nameColumn, String idColumn, String constraint, String kind) {
        boolean hasCheck() {
            return !constraint.equals("-");
        }
    }

    private static List<Row> list() throws Exception {
        List<Row> rows = new ArrayList<>();
        for (String line : Files.readAllLines(LIST)) {
            if (line.isBlank() || line.startsWith("#") || line.startsWith("table\t")) continue;
            String[] f = line.split("\t");
            assertThat(f).as("a row of the list has five columns: %s", line).hasSize(5);
            rows.add(new Row(f[0], f[1], f[2], f[3], f[4]));
        }
        return rows;
    }

    @Test
    void theListAndTheChangelogNameTheSameConstraints() throws Exception {
        List<Row> rows = list();
        assertThat(rows).as("non-vacuity: the list has rows").hasSizeGreaterThan(20);
        String xml = Files.readString(CHANGELOG_FILE);
        // The forward text names each constraint in an ADD CONSTRAINT, the rollback in a DROP CONSTRAINT IF EXISTS.
        Matcher adds = Pattern.compile("ADD CONSTRAINT (\\w+_(?:id_check|collection_id_not_null))\\b").matcher(xml);
        List<String> added = new ArrayList<>();
        while (adds.find()) added.add(adds.group(1));
        Matcher drops = Pattern.compile("DROP CONSTRAINT IF EXISTS (\\w+_(?:id_check|collection_id_not_null))\\b").matcher(xml);
        List<String> dropped = new ArrayList<>();
        while (drops.find()) dropped.add(drops.group(1));
        List<String> listed = rows.stream().filter(Row::hasCheck).map(Row::constraint).toList();
        assertThat(listed).as("every listed constraint is unique").doesNotHaveDuplicates();
        assertThat(added).as("the changelog adds exactly the listed constraints").containsExactlyInAnyOrderElementsOf(listed);
        assertThat(dropped).as("the changelog's rollbacks drop exactly the listed constraints (R5)")
            .containsExactlyInAnyOrderElementsOf(listed);
    }

