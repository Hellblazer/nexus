/**
 * RDR-229 P3.1 stage 1 (nexus-p2m1x.17): the expand changeset, {@code vectors-068-collection-id-expand.xml}.
 *
 * <p>What the changeset adds: {@code catalog_collections.collection_id} (GENERATED BY DEFAULT AS IDENTITY, filled by
 * the changeset, with UNIQUE (tenant_id, collection_id) and UNIQUE (tenant_id, collection_id, embedding_model)); a
 * nullable id column beside every name column of the Expand list; and, NOT VALID, a CHECK that ties each id to its
 * name ({@code (NULLIF(name,'') IS NULL) = (id IS NULL)}, so '' means unset; {@code superseded_by}'s own form) plus
 * {@code CHECK (collection_id IS NOT NULL)} on chunks and taxonomy_centroids. The columns and the constraint names are
 * ONE list, {@code src/main/resources/db/rdr229/p31-checks.tsv}, which R5's operator down-step is generated from later;
 * this class reads the same list and pins the changelog against it.
 *
 * <p>Cases: a fresh walk applies every changeset; an upgrade walk over seeded rows rewrites no row of a user-data table
 * (xmin and relfilenode unchanged) and fills the registry's ids; every CHECK has the semantics the ruling gives (a
 * non-empty name with a NULL id is refused with 23514, '' with a NULL id passes); the three pre-P3.1 write shapes
 * fail with 23514 (R5); the queue changesets are no-ops when the table is absent and apply when a store kept it (R3);
 * the rollback removes every listed constraint and keeps the id columns, and the walk goes forward again (R5).
 */
