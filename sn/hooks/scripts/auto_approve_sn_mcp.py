"""Auto-approve sn plugin read tools (Serena + Context7) by explicit full name.

Reads only (nexus-2lf1v): Serena's writers and the ``NOT_AUTO_APPROVED`` tools
get no decision, so Claude Code's own permission flow decides. See
``SERENA_READ_TOOLS``.

Declared in exec form (RDR-215 bead nexus-q02nx.23; launcher nexus-j4iy0) as
``uv tool run --directory ${CLAUDE_PLUGIN_ROOT} --no-config --quiet --python >=3.12
python ${CLAUDE_PLUGIN_ROOT}/hooks/scripts/auto_approve_sn_mcp.py``, with
the hook payload on stdin and no argv, so the snapshot resolves to the
sibling serena-tools.txt. The bash wrapper it replaces passed that path
explicitly AND ended in an unconditional ``exit 0`` that hid a Python crash
completely; the wrapper is gone, so main() runs inside _hook_boundary.guard
instead -- a crash is logged to stderr rather than either swallowed or
fatal. That snapshot is generated by
scripts/sync_sn_serena_tools.py from the Serena revision pinned in
sn/.mcp.json (nexus-jbt5x: a hand-kept case list fell five tools behind and
every one of them prompted). No wildcards: a Serena tool the snapshot does
not name is not approved. Context7 has two tools and they are named here.

Event-aware output: PermissionRequest fires only when a prompt would be
shown; under defaultMode:auto the classifier decides first and never
consults it (cc-validation scenario 16, measured), so the same allowlist is
also registered on PreToolUse, where permissionDecision=allow lands before
the classifier. One allowlist, two events.

Worktree guard (nexus-ftpk3, refined nexus-ebx0s round 2): before the
allowlist is consulted, a Serena WRITE tool is DENIED whenever its call's
cwd does not match this session's own Serena root. That root is a RECORD
this session made of its own startup cwd (``session_start.py``, only on
``source == "startup"``) when one exists; only when it does not (no
session_id, or nothing was ever recorded) does this fall back to the
pre-round-2 cwd-only check -- deny when the call's cwd is itself a linked
git worktree, the shape a worktree-dispatched subagent sharing the parent's
primary-rooted server has for its whole life. Both branches, the ordering
between them, and every message live in ``worktree_guard.write_denial_reason``
(shared with subagent_start.py's detector). Three incidents motivated the
original cwd-only check; round 2 additionally covers a RELOCATED session
(cwd never actually leaves the primary while Serena is rooted elsewhere)
without re-denying a session that legitimately started inside a worktree,
which the cwd-only check could not tell apart from the relocated shape.

Stdlib only: hooks run under system python with no conexus installed.
"""
from __future__ import annotations

import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import _hook_boundary  # noqa: E402 — bundled sibling, resolved by the path insert above

# Imported at module scope, ahead of the boundary, ON PURPOSE. subagent_start.py
# guards the identical import and degrades to "not a worktree"; here that would
# be wrong. This module's dependency IS the guard: with worktree_guard gone, the
# allowlist below would happily approve mcp__plugin_sn_serena__replace_in_files
# from a linked worktree, which is the incident (nexus-ftpk3, three of them)
# worktree_guard.py exists to prevent. Refusing to start means every sn tool
# prompts for manual approval, which is noisy and safe; degrading means the
# guard is silently off, which is quiet and not. Do not "make this consistent"
# with its sibling — the asymmetry is the decision.
from worktree_guard import cwd_from_payload, is_serena_write_tool, write_denial_reason  # noqa: E402

CONTEXT7_TOOLS = frozenset({
    "mcp__plugin_sn_context7__resolve-library-id",
    "mcp__plugin_sn_context7__query-docs",
})
SERENA_PREFIX = "mcp__plugin_sn_serena__"

#: Serena tools this hook approves: reads only (nexus-2lf1v, Sam 2026-09-29).
#: A PreToolUse allow skips both the user's prompt and the auto-mode
#: classifier, so approving a file or memory writer, or jet_brains_debug (which
#: evaluates arbitrary Groovy/Java in the IDE's JVM), would remove the only
#: check on it; those get no decision here and Claude Code decides, as it does
#: for its own Edit and Write. Default-deny: a tool the snapshot adds is not
#: approved until it is named here, and tests/test_sn_plugin.py fails until
#: every snapshot tool is classified as a read, a write
#: (worktree_guard.SERENA_WRITE_TOOLS) or NOT_AUTO_APPROVED.
#:
#: "Read" here means this plugin checked what the tool does at the pinned
#: Serena revision, not that Serena calls it read-only: Serena's own test is
#: only the absence of its CanEdit marker, which jet_brains_debug also lacks.
SERENA_READ_TOOLS: frozenset[str] = frozenset({
    "find_declaration",
    "find_implementations",
    "find_referencing_symbols",
    "find_symbol",
    "get_current_config",
    "get_diagnostics_for_file",
    "get_diagnostics_for_symbol",
    "get_symbols_overview",
    "initial_instructions",
    "jet_brains_find_declaration",
    "jet_brains_find_implementations",
    "jet_brains_find_referencing_symbols",
    "jet_brains_find_symbol",
    "jet_brains_get_symbols_overview",
    "jet_brains_list_inspections",
    "jet_brains_run_inspections",
    "jet_brains_type_hierarchy",
    "list_memories",
    "list_queryable_projects",
    "read_memory",
    "serena_info",
})
#: Not writers through the project root, and still never approved: each can do
#: something a read cannot. Distinct from the sync script's NEVER_APPROVE,
#: which keeps tools out of the snapshot altogether.
NOT_AUTO_APPROVED: frozenset[str] = frozenset({
    "jet_brains_debug",  # evaluates arbitrary Groovy/Java in the IDE's JVM
    "onboarding",  # seeds .serena/memories/memory_maintenance.md when absent
    "query_project",  # runs any tool Serena calls read-only (no CanEdit marker) in another project, jet_brains_debug included
    "restart_language_server",
})


def allowed_tools(snapshot: pathlib.Path) -> frozenset[str]:
    """Context7's two tools, plus every snapshot tool that is a read."""
    names = set(CONTEXT7_TOOLS)
    try:
        lines = snapshot.read_text().splitlines()
    except OSError:
        return frozenset(names)  # snapshot missing: Serena tools prompt, nothing else changes
    for line in lines:
        line = line.strip()
        if line and not line.startswith("#") and line in SERENA_READ_TOOLS:
            names.add(SERENA_PREFIX + line)
    return frozenset(names)


def decide(payload: str, snapshot: pathlib.Path) -> str:
    """Return the JSON envelope for an allowed tool, else an empty string."""
    try:
        data = json.loads(payload)
    except (ValueError, TypeError):
        return ""
    if not isinstance(data, dict):
        return ""
    tool_name = data.get("tool_name", "")
    event = data.get("hook_event_name", "PermissionRequest")
    if is_serena_write_tool(tool_name):
        cwd = cwd_from_payload(payload)
        session_id = data.get("session_id", "")
        session_id = session_id if isinstance(session_id, str) else ""
        reason = write_denial_reason(tool_name, cwd, session_id)
        if reason is not None:
            if event == "PreToolUse":
                out = {
                    "hookEventName": "PreToolUse",
                    "permissionDecision": "deny",
                    "permissionDecisionReason": reason,
                }
            else:
                out = {
                    "hookEventName": "PermissionRequest",
                    "decision": {"behavior": "deny", "message": reason},
                }
            return json.dumps({"hookSpecificOutput": out})
    if tool_name not in allowed_tools(snapshot):
        return ""
    if event == "PreToolUse":
        out = {
            "hookEventName": "PreToolUse",
            "permissionDecision": "allow",
            "permissionDecisionReason": "plugin allowlist (auto-approve)",
        }
    else:
        out = {"hookEventName": "PermissionRequest", "decision": {"behavior": "allow"}}
    return json.dumps({"hookSpecificOutput": out})


def main() -> int:
    snapshot = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else pathlib.Path(__file__).with_name("serena-tools.txt")
    result = decide(sys.stdin.read(), snapshot)
    if result:
        print(result)  # noqa: T201 — stdout IS this hook's decision channel
    return 0


if __name__ == "__main__":
    sys.exit(_hook_boundary.guard(main, "sn-auto-approve"))
