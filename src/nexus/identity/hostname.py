"""Which machine a binding's ``host`` names (RDR-253; GitHub issue 1679).

A binding records ``host`` and the holder check asks "is that process on THIS machine". ``socket.gethostname()`` answers
that badly: on a laptop it follows DHCP and VPN and changes between days (``ip-10-122-0-102.ec2.internal``, then
``-105``), so a resumed session met its own old binding as "another host", judged it by its lease alone and, the lease
still being live, was refused the seat although the holder pid was dead on this very machine.

``this_host()`` is therefore a key derived from an identifier the OS keeps for the life of the install:

* macOS: ``IOPlatformUUID`` (the hardware UUID, ``ioreg``). Not ``LocalHostName``: Migration Assistant copies it to the
  new Mac, so two machines can carry the same one.
* Linux: ``/etc/machine-id``, in the initial pid namespace only (below).
* Windows: the ``MachineGuid`` value under ``HKLM\\SOFTWARE\\Microsoft\\Cryptography``.

The key is ``nxh1-`` plus 128 bits of ``HMAC-SHA256(identifier, "nexus.identity.host.v1:<source>")``: the raw identifier
never leaves the machine (``machine-id(5)`` asks for exactly this), and two keys are equal only when the identifiers and
sources are equal, or by an HMAC collision (2**-128 for a pair). A key is never cached on disk: a copied config directory
would carry it to another machine.

**A false "same host" is the dangerous direction**: the pid probe and registry read of THIS machine would then judge a
holder on another machine, find no such pid, and free a live seat. So the key is refused (and ``this_host()`` falls back
to ``gethostname()``, today's behaviour, never a weaker one) whenever the identifier could be shared by two pid tables:

* a Linux machine id that is empty, ``uninitialized``, all zeros, not 32 hex digits or not readable;
* a Linux process outside the initial pid namespace (a container that bind-mounts the host's ``/etc/machine-id``, as
  toolbox and devcontainers do, has a different process table from the host's);
* no readable identifier at all (``ioreg`` missing, timing out or, under a sandbox that denies IOKit, answering an empty
  dictionary; no registry value; another OS). On macOS and Windows that is logged once as ``host_key_unavailable``.

A failed probe is retried once at once and then not asked again for :data:`PROBE_RETRY_S`, so a sandboxed process does not
spawn ``ioreg`` on every call and a transient failure does not fix the process on ``gethostname()`` for its life. A
success is kept for the life of the process.

What stays possible: a machine image cloned without regenerating the identifier (a VM clone, an AMI baked with a filled
``/etc/machine-id``) gives two machines one key. That is the same class of fault as two machines named ``localhost`` today,
and the identifiers are regenerated by the platforms' own cloning tools (``systemd-firstboot``, sysprep).

**Rows under a name that is not a key** (written before the key existed, or by a machine with no key) carry
``gethostname()``. A name is not proof of locality: two machines can be called ``ubuntu``, and a machine that changed networks
no longer answers to the name it had. A row under a non-key name counts as this machine's only on LOCAL PROOF
(:func:`holder_is_local`): a token file in this machine's identity directory for the holder's (pid, ``startedAt``) that
records that same host, or the very process asking (its own pid and ``startedAt``, which it read from its own registry
file). A key names exactly one machine and needs no proof, only equality with this machine's.

The proof can be wrong when the identity directory is shared or copied between machines (an NFS home, an rsync of
``~/.config/nexus``): machine A then sees machine B's token files and accepts B's pre-key hostname as its own, and judges
B's holder by A's pid table. That is the same trust the token files already carry (``clean_local_files`` deletes by them);
it concerns only rows written under a non-key name, which stop being written once both machines run this client; and a
shared directory already weakens the registry-directory leg of :func:`nexus.identity.holder.check_holder`.

Listing queries (the engine is asked for the bindings under each name this machine has used) are not judgements: they may
ask under every name this machine is known by (:func:`listing_names`), and the proof is applied to each holder afterwards.
"""
from __future__ import annotations

import hmac
import os
import re
import socket
import subprocess
import sys
import time
from collections.abc import Callable, Mapping
from hashlib import sha256
from pathlib import Path
from typing import Any

import structlog

_log = structlog.get_logger(__name__)

KEY_PREFIX = "nxh1-"
_DOMAIN = b"nexus.identity.host.v1:"
#: ``readlink /proc/self/ns/pid`` of the initial pid namespace (the kernel's PROC_PID_INIT_INO), the same on every boot.
INIT_PID_NS = "pid:[4026531836]"
#: macOS ships it here; an absolute path no PATH or working directory can change.
_IOREG = "/usr/sbin/ioreg"
_MACHINE_ID_FILES = (Path("/etc/machine-id"), Path("/var/lib/dbus/machine-id"))
_HEX32 = re.compile(r"[0-9a-f]{32}")
_UUID = re.compile(r"[0-9A-Fa-f]{8}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{12}")
_IOREG_UUID = re.compile(r'"IOPlatformUUID"\s*=\s*"([^"]+)"')
#: How long a failed probe is not repeated (a retry is made at once, then this long is waited).
PROBE_RETRY_S = 60.0


def host_key(source: str, identifier: str) -> str:
    """The key of one machine identifier: ``nxh1-<32 hex>``."""
    digest = hmac.new(identifier.strip().lower().encode("utf-8"), _DOMAIN + source.encode("ascii"), sha256).hexdigest()
    return KEY_PREFIX + digest[:32]


def _macos_uuid(run: Callable[..., Any] | None) -> str | None:
    if run is None:
        from nexus.bounded_subprocess import run_bounded  # noqa: PLC0415 — deferred: hook import cost

        run = run_bounded
    try:
        out = run([_IOREG, "-rd1", "-c", "IOPlatformExpertDevice"], timeout=5, stderr=subprocess.DEVNULL, check=True).stdout
    except Exception:  # noqa: BLE001 — no ioreg, a timeout, a failure: no identifier
        return None
    found = _IOREG_UUID.search(str(out))
    return found.group(1) if found and _UUID.fullmatch(found.group(1)) else None


def _linux_machine_id(read: Callable[[Path], str], pid_ns: Callable[[], str]) -> str | None:
    try:
        if pid_ns() != INIT_PID_NS:
            return None    # a container's process table is not the host's, whatever machine-id it can read
    except OSError:
        return None
    for path in _MACHINE_ID_FILES:
        try:
            text = read(path).strip().lower()
        except (OSError, ValueError):     # ValueError: the UnicodeDecodeError of a file that is not ASCII
            continue
        if _HEX32.fullmatch(text) and text != "0" * 32:
            return text
        return None        # empty, "uninitialized" or malformed: the file says there is no usable id
    return None


def _windows_machine_guid() -> str | None:
    try:
        import winreg  # noqa: PLC0415 — Windows only

        with winreg.OpenKey(winreg.HKEY_LOCAL_MACHINE, r"SOFTWARE\Microsoft\Cryptography",
                            0, winreg.KEY_READ | winreg.KEY_WOW64_64KEY) as key:
            value, _kind = winreg.QueryValueEx(key, "MachineGuid")
    except Exception:  # noqa: BLE001 — no such value, no access: no identifier
        return None
    return value if isinstance(value, str) and _UUID.fullmatch(value.strip()) else None


def stable_host(*, platform: str | None = None, run: Callable[..., Any] | None = None,
                read: Callable[[Path], str] | None = None, pid_ns: Callable[[], str] | None = None,
                windows_guid: Callable[[], str | None] | None = None) -> str | None:
    """This machine's key (:func:`host_key`), or None when no identifier that is safe to equate is available (the module
    docstring lists the refusals). The keyword arguments are the test seams; the defaults read the real machine."""
    system = platform if platform is not None else sys.platform
    if system == "darwin":
        ident, source = _macos_uuid(run), "ioplatformuuid"
    elif system.startswith("linux"):
        ident = _linux_machine_id(read or (lambda p: p.read_text(encoding="ascii")),
                                  pid_ns or (lambda: os.readlink("/proc/self/ns/pid")))
        source = "machine-id"
    elif system == "win32":
        ident, source = (windows_guid or _windows_machine_guid)(), "machineguid"
    else:
        return None
    return host_key(source, ident) if ident else None


_probe: dict[str, Any] = {"key": None, "failed_at": None, "warned": False}


def _stable_host_cached() -> str | None:
    """The probe for this process: a success is kept, a failure retried once now and then not asked again for
    :data:`PROBE_RETRY_S`; a platform that should have an identifier and gave none is logged once."""
    if _probe["key"] is not None:
        return _probe["key"]
    failed = _probe["failed_at"]
    if failed is not None and time.monotonic() - failed < PROBE_RETRY_S:
        return None
    key = stable_host() or stable_host()
    if key is not None:
        _probe["key"], _probe["failed_at"] = key, None
        return key
    _probe["failed_at"] = time.monotonic()
    if sys.platform in ("darwin", "win32") and not _probe["warned"]:
        _probe["warned"] = True
        _log.warning("host_key_unavailable", platform=sys.platform, fallback="gethostname",
                     consequence="bindings name this machine by its hostname, which a network change renames")
    return None


def this_host() -> str:
    """The name bindings carry for this machine: its stable key, else ``gethostname()``, escaped when the hostname itself
    starts with the key prefix, so a fallback name can never be read as a key (:func:`is_key`)."""
    key = _stable_host_cached()
    if key is not None:
        return key
    name = socket.gethostname()
    return f"host-{name}" if name.startswith(KEY_PREFIX) else name


def is_key(name: object) -> bool:
    return isinstance(name, str) and name.startswith(KEY_PREFIX)


def describe_host(host: object) -> str:
    """*host* for a person: this machine's key as ``<hostname> (<key>)``, another machine's key as ``another machine
    (<key>)`` (the engine records no hostname), any other name as it is."""
    if not isinstance(host, str):
        return str(host)
    if not is_key(host):
        return host
    return f"{socket.gethostname()} ({host})" if host == this_host() else f"another machine ({host})"


def _short(host: object) -> str:
    return str(host or "").split(".")[0]


def machine_short_names(here: str) -> frozenset[str]:
    """The short forms (up to the first dot) of the names a ref written by hand can give for *here*'s machine: its own name,
    and its ``gethostname()`` when *here* is this machine's key (lab-remote's ``labrun`` row names the machine that way)."""
    names = {_short(here)}
    if here == this_host():
        names.add(_short(socket.gethostname()))
    return frozenset(n for n in names if n)


