"""Which machine a binding's ``host`` names (RDR-253; GitHub issue 1679).

A binding records ``host`` and the holder check asks "is that process on THIS machine". ``socket.gethostname()`` answers
that badly: on a laptop it follows DHCP and VPN and changes between days (``ip-10-122-0-102.ec2.internal``, then
``-105``), so a resumed session met its own old binding as "another host", judged it by its lease alone and, the lease
still being live, was refused the seat although the holder pid was dead on this very machine.

``this_host()`` is therefore a key derived from an identifier the OS keeps for the life of the install:

* macOS: ``IOPlatformUUID`` (the hardware UUID, ``ioreg``). Not ``LocalHostName``: Migration Assistant copies it to the
  new Mac, so two machines can carry the same one.
* Linux: ``/etc/machine-id``, in the initial pid namespace only (below).
* Windows: ``HKLM\\SOFTWARE\\Microsoft\\Cryptography\\MachineGuid``.

The key is ``nxh1-`` plus 128 bits of ``HMAC-SHA256(identifier, "nexus.identity.host.v1:<source>")``: the raw identifier
never leaves the machine (``machine-id(5)`` asks for exactly this), and two keys are equal only when the identifiers and
sources are equal, or by an HMAC collision (2**-128 for a pair).

**A false "same host" is the dangerous direction**: the pid probe and registry read of THIS machine would then judge a
holder on another machine, find no such pid, and free a live seat. So the key is refused (and ``this_host()`` falls back
to ``gethostname()``, today's behaviour, never a weaker one) whenever the identifier could be shared by two pid tables:

* a Linux machine id that is empty, ``uninitialized``, all zeros or not 32 hex digits;
* a Linux process outside the initial pid namespace (a container that bind-mounts the host's ``/etc/machine-id``, as
  toolbox and devcontainers do, has a different process table from the host's);
* no readable identifier at all (``ioreg`` missing or timing out, no registry value, another OS).

What stays possible: a machine image cloned without regenerating the identifier (a VM clone, an AMI baked with a filled
``/etc/machine-id``) gives two machines one key. That is the same class of fault as two machines named ``localhost`` today,
and the identifiers are regenerated by the platforms' own cloning tools (``systemd-firstboot``, sysprep).

Rows written before this change carry ``gethostname()`` as their host. :func:`local_names` lists the names this machine
answers to (the key first, then the current ``gethostname()``), so such a row still counts as this host when the name has
not changed since it was written. A row written under a name the machine no longer has cannot be recognised and is judged by
its lease, once (it lapses in five minutes and its seat frees ten minutes after that).
"""
from __future__ import annotations

import functools
import hmac
import os
import re
import socket
import subprocess
import sys
from collections.abc import Callable, Iterable, Mapping
from hashlib import sha256
from pathlib import Path
from typing import Any

KEY_PREFIX = "nxh1-"
_DOMAIN = b"nexus.identity.host.v1:"
#: ``readlink /proc/self/ns/pid`` of the initial pid namespace (the kernel's PROC_PID_INIT_INO), the same on every boot.
INIT_PID_NS = "pid:[4026531836]"
_MACHINE_ID_FILES = (Path("/etc/machine-id"), Path("/var/lib/dbus/machine-id"))
_HEX32 = re.compile(r"[0-9a-f]{32}")
_UUID = re.compile(r"[0-9A-Fa-f]{8}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{12}")
_IOREG_UUID = re.compile(r'"IOPlatformUUID"\s*=\s*"([^"]+)"')


def host_key(source: str, identifier: str) -> str:
    """The key of one machine identifier: ``nxh1-<32 hex>``."""
    digest = hmac.new(identifier.strip().lower().encode("utf-8"), _DOMAIN + source.encode("ascii"), sha256).hexdigest()
    return KEY_PREFIX + digest[:32]


def _macos_uuid(run: Callable[..., Any] | None) -> str | None:
    if run is None:
        from nexus.bounded_subprocess import run_bounded  # noqa: PLC0415 — deferred: hook import cost

        run = run_bounded
    try:
        from nexus.util.nx_argv import argv_off_cwd  # noqa: PLC0415

        out = run(argv_off_cwd(["ioreg", "-rd1", "-c", "IOPlatformExpertDevice"]), timeout=5, stderr=subprocess.DEVNULL,
                  check=True).stdout
    except Exception:  # noqa: BLE001 — no ioreg, a timeout, a failure: no identifier
        return None
    found = _IOREG_UUID.search(str(out))
    return found.group(1) if found and _UUID.fullmatch(found.group(1)) else None


def _linux_machine_id(read: Callable[[Path], str], pid_ns: Callable[[], str]) -> str | None:
    try:
        if pid_ns() != INIT_PID_NS:
            return None    # a container's process table is not the host's, whatever machine-id it can read
    except OSError:
        return None
    for path in _MACHINE_ID_FILES:
        try:
            text = read(path).strip().lower()
        except OSError:
            continue
        if _HEX32.fullmatch(text) and text != "0" * 32:
            return text
        return None        # empty, "uninitialized" or malformed: the file says there is no usable id
    return None


def _windows_machine_guid() -> str | None:
    try:
        import winreg  # noqa: PLC0415 — Windows only

        with winreg.OpenKey(winreg.HKEY_LOCAL_MACHINE, r"SOFTWARE\Microsoft\Cryptography",
                            0, winreg.KEY_READ | winreg.KEY_WOW64_64KEY) as key:
            value, _kind = winreg.QueryValueEx(key, "MachineGuid")
    except Exception:  # noqa: BLE001 — no such value, no access: no identifier
        return None
    return value if isinstance(value, str) and _UUID.fullmatch(value.strip()) else None


def stable_host(*, platform: str | None = None, run: Callable[..., Any] | None = None,
                read: Callable[[Path], str] | None = None, pid_ns: Callable[[], str] | None = None,
                windows_guid: Callable[[], str | None] | None = None) -> str | None:
    """This machine's key (:func:`host_key`), or None when no identifier that is safe to equate is available (the module
    docstring lists the refusals). The keyword arguments are the test seams; the defaults read the real machine."""
    system = platform if platform is not None else sys.platform
    if system == "darwin":
        ident, source = _macos_uuid(run), "ioplatformuuid"
    elif system.startswith("linux"):
        ident = _linux_machine_id(read or (lambda p: p.read_text(encoding="ascii")),
                                  pid_ns or (lambda: os.readlink("/proc/self/ns/pid")))
        source = "machine-id"
    elif system == "win32":
        ident, source = (windows_guid or _windows_machine_guid)(), "machineguid"
    else:
        return None
    return host_key(source, ident) if ident else None


@functools.cache
def _stable_host_cached() -> str | None:
    return stable_host()


def this_host() -> str:
    """The name bindings carry for this machine: its stable key, else ``gethostname()``. One probe per process."""
    return _stable_host_cached() or socket.gethostname()


def machine_names() -> tuple[str, ...]:
    """Every name this machine answers to now: :func:`this_host` first, then ``gethostname()`` when it differs (a binding
    written before the key existed carries it)."""
    first = this_host()
    legacy = socket.gethostname()
    return (first,) if legacy == first else (first, legacy)


def local_names(procs: Any, host: str) -> tuple[str, ...]:
    """The names for *host*'s machine. ``procs.names`` when *host* is one of them (a test stand-in that sets it); else
    :func:`machine_names` when *host* is this machine's own name now; else just *host*: any other host is another machine
    (or a test's invented one) and answers to no second name."""
    names = getattr(procs, "names", None)
    if names and host in names:
        return tuple(names)
    return machine_names() if host == this_host() else (host,)


def is_local(holder_host: object, names: Iterable[str]) -> bool:
    """Whether a binding's ``host`` is one of this machine's *names*."""
    return isinstance(holder_host, str) and holder_host in tuple(names)


def bindings_here(client: Any, procs: Any, host: str, pid: int | None = None) -> list[dict[str, Any]]:
    """The live and lapsed bindings held on this machine (:meth:`IdentityClient.bindings_by_host` under each of its
    names, an identity once), the ones under *host* first."""
    seen: dict[str, dict[str, Any]] = {}
    for name in local_names(procs, host):
        for view in client.bindings_by_host(name, pid) if pid is not None else client.bindings_by_host(name):
            seen.setdefault(str(view.get("id")), view)
    return list(seen.values())


def history_here(client: Any, procs: Any, host: str, pid: int, proc_start: str) -> list[dict[str, Any]]:
    """Every identity that ever held the process (*pid*, *proc_start*) on this machine, under any of its names, most
    recent first (by the engine's order within one name; the name *host* first)."""
    rows: list[dict[str, Any]] = []
    for name in local_names(procs, host):
        rows.extend(client.history(name, pid, proc_start))
    return rows


def holder_host_of(view: Mapping[str, Any]) -> str | None:
    holder = view.get("holder")
    return holder.get("host") if isinstance(holder, Mapping) else None
