def _token_hosts(identity_dir: Path | None) -> list[str]:
    """The hosts this machine's own token files record (a name this machine bound under, whatever it is called now)."""
    if identity_dir is None:
        return []
    from nexus.identity.token_file import read_token_file, token_files  # noqa: PLC0415 — token_file imports holder lazily

    found: list[str] = []
    for path in token_files(identity_dir):
        record = read_token_file(path)
        if record is not None and record.host and record.host not in found:
            found.append(record.host)
    return found


def listing_names(host: str, identity_dir: Path | None = None) -> tuple[str, ...]:
    """The names to ask the engine for this machine's bindings under: *host*, the current ``gethostname()`` when *host* is
    this machine's key, and every host this machine's own token files record. A listing is not a judgement."""
    names = [host]
    if host == this_host() and socket.gethostname() not in names:
        names.append(socket.gethostname())
    names.extend(h for h in _token_hosts(identity_dir) if h not in names)
    return tuple(names)


def holder_is_local(holder: Mapping[str, Any], *, host: str, identity_dir: Path | None = None,
                    process: tuple[int, int | None] | None = None) -> bool:
    """Whether *holder* (``{host, pid, started_at, ...}``) is a process on this machine, whose current name is *host*.
    The holder's host is *host* itself: yes. A key that is not *host*: no (a key names one machine). Any other name: only
    on local proof (module docstring): a token file in *identity_dir* for the holder's (pid, ``startedAt``) recording that
    host, or *process* (the pid and ``startedAt`` of the caller itself) equal to the holder's."""
    name = holder.get("host")
    if not isinstance(name, str):
        return False
    if name == host:
        return True
    if is_key(name):
        return False
    pid, started = holder.get("pid"), holder.get("started_at")
    if not isinstance(pid, int) or isinstance(pid, bool) or not isinstance(started, int) or isinstance(started, bool):
        return False
    if process is not None and process == (pid, started):
        return True
    if identity_dir is None:
        return False
    from nexus.identity.token_file import read_token_file, token_path  # noqa: PLC0415 — token_file imports holder lazily

    record = read_token_file(token_path(identity_dir, pid, started))
    return record is not None and record.host == name


def bindings_here(client: Any, host: str, pid: int | None = None, identity_dir: Path | None = None) -> list[dict[str, Any]]:
    """The live and lapsed bindings on this machine: :meth:`IdentityClient.bindings_by_host` under each of
    :func:`listing_names`, an identity once, the ones under *host* first. The caller judges each holder."""
    seen: dict[str, dict[str, Any]] = {}
    for name in listing_names(host, identity_dir):
        for view in client.bindings_by_host(name, pid) if pid is not None else client.bindings_by_host(name):
            seen.setdefault(str(view.get("id")), view)
    return list(seen.values())


def history_here(client: Any, host: str, pid: int, proc_start: str, identity_dir: Path | None = None) -> list[dict[str, Any]]:
    """Every identity that ever held the process (*pid*, *proc_start*) under any of :func:`listing_names`, the name *host*
    first."""
    rows: list[dict[str, Any]] = []
    for name in listing_names(host, identity_dir):
        rows.extend(client.history(name, pid, proc_start))
    return rows
