def test_generation_over_the_real_tree_is_byte_identical_across_hash_seeds(tmp_path: Path) -> None:
    outs = []
    for seed in ("1", "2"):
        out = tmp_path / f"seed-{seed}.json"
        env = {**os.environ, "PYTHONHASHSEED": seed}
        subprocess.run([sys.executable, str(Path(inv.__file__).resolve()), "--write", "--pinned", str(out),
                        "--source-sha", "fixed"], env=env, check=True, capture_output=True, timeout=300)
        outs.append(out.read_bytes())
    assert outs[0] and outs[0] == outs[1]


def test_python_registries_are_recorded_entry_by_entry(pinned: dict) -> None:
    """Cross-checked against the standard-library syntax tree, an independent reader of the same
    literal: the container row holds exactly the entries the tuple has, and every entry that
    names a table is a row of its own."""
    rows = {r["id"]: r for r in pinned["rows"] if r["source"] == "python"}
    tree = ast.parse((inv.REPO_ROOT / "src/nexus/health.py").read_text(encoding="utf-8"))
    (rls,) = [n for n in ast.walk(tree)
              if isinstance(n, ast.AnnAssign) and getattr(n.target, "id", "") == "_RLS_TENANT_TABLES"]
    expected = [e.value for e in rls.value.elts]
    container = rows["python:src/nexus/health.py#_RLS_TENANT_TABLES"]
    assert [e.strip('"') for e in container["entries"]] == expected
    for table in inv.TABLES:
        assert f"python:src/nexus/health.py#_RLS_TENANT_TABLES:nexus.{table}" in rows, table
    # a registry the first version missed: the pre-unify list names catalog_document_chunks too
    assert "python:src/nexus/db/chash_tables.py#LEGACY_CHASH_BEARING_TABLES:nexus.catalog_document_chunks" in rows
    assert "python:src/nexus/db/chash_tables.py#CHASH_BEARING_TABLES:nexus.catalog_document_chunks" in rows
    assert "python:src/nexus/db/chash_tables.py#CHASH_BEARING_TABLES:CHUNKS_TABLE" in rows
