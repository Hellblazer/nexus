def test_inventory_is_non_vacuous(real: inv.Roots, pinned: dict) -> None:
    """A scanner that silently matched nothing would also be 'current' (the
    nexus-moht0 vacuous-gate class), so pin floors measured on 2026-10-06."""
    rows = pinned["rows"]
    assert len(rows) >= 600
    assert len(list(real.changelog_dir.glob("*.xml"))) >= CHANGELOG_FILES
    kinds = {r["kind"] for r in rows}
    assert {"fk", "constraint", "index", "policy", "rls", "trigger", "view", "function", "do-block", "dml",
            "grant-schema-wide", "java-method", "python-anchor", "table"} <= kinds
    for table in inv.TABLES:
        sql = [r for r in rows if r["source"] == "changelog" and table in r["tables"]]
        java = [r for r in rows if r["source"] == "java" and table in r["tables"]]
        assert len(sql) >= 5, f"{table}: only {len(sql)} changelog rows"
        assert len(java) >= 1, f"{table}: no Java row"
    writers = [r for r in rows if r["source"] == "java"
               and any(s["verb"] == "INSERT" for s in r["sites"])]
    assert len(writers) >= 8
    # rows carry their forms
    for r in rows:
        assert r["rdr_row"] in {t["id"] for t in pinned["td_rows"]}
        assert r["new_form"] and r["fallback_form"]


